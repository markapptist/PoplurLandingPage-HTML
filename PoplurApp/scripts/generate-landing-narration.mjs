// macOS maintainer utility; recordings are committed, so deployment needs no TTS service.
// Edit src/landing/narration-copy.json when the landing copy changes, then run this script.
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { tmpdir } from 'node:os'
import path from 'node:path'
const root = fileURLToPath(new URL('..', import.meta.url))
const copy = JSON.parse(readFileSync(path.join(root, 'src/landing/narration-copy.json'), 'utf8'))
const output = path.join(root, 'public/audio/landing')
const scratch = mkdtempSync(path.join(tmpdir(), 'poplur-narration-'))
const tracks = {}
mkdirSync(output, { recursive: true })
try {
  for (const [id, text] of Object.entries(copy)) {
    const script = path.join(scratch, id + '.txt'), speech = path.join(scratch, id + '.aiff')
    writeFileSync(script, text)
    execFileSync('/usr/bin/say', ['-v', 'Samantha', '-r', '170', '-f', script, '-o', speech])
    const encoded = path.join(scratch, id + '.mp3')
    execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', speech, '-af', 'loudnorm=I=-16:TP=-1.5:LRA=9', '-ar', '44100', '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '64k', '-map_metadata', '-1', encoded])
    const bytes = readFileSync(encoded), hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12)
    const file = `${id}-${hash}.mp3`
    writeFileSync(path.join(output, file), bytes)
    const info = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'json', encoded], { encoding: 'utf8' }))
    const duration = Number(info.format.duration)
    if (!(duration > 1) || bytes.length < 1000) throw new Error('Empty narration: ' + id)
    tracks[id] = { src: '/audio/landing/' + file, text, duration }
    console.log(`${id}: ${duration.toFixed(1)} s, ${bytes.length} bytes`)
  }
  writeFileSync(path.join(root, 'src/landing/narrationTracks.mjs'), '// Generated by scripts/generate-landing-narration.mjs from narration-copy.json.\n/** @type {Record<string, { src: string; text: string; duration: number }>} */\nexport const NARRATION_TRACKS = ' + JSON.stringify(tracks, null, 2) + '\n')
} finally { rmSync(scratch, { recursive: true, force: true }) }
